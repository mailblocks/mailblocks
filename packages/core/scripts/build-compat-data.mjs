// Turns data/caniemail.json (Can I Email API dump) into src/generated/caniemail.ts:
// one entry per feature with only the latest tested version per client platform.
//
// Run: pnpm data:build

import { readFileSync, writeFileSync } from 'node:fs';

const SOURCE = 'data/caniemail.json';
const TARGET = 'src/generated/caniemail.ts';

// JSON.parse enumerates integer-like keys ("2019", "12") before all others, which
// destroys the oldest-to-newest order Can I Email uses for versions. Prefix every
// key that starts with a digit so it is no longer integer-like, then strip the mark.
const MARK = '§'; // "§": printable, valid inside JSON strings, never a real key prefix
const raw = readFileSync(SOURCE, 'utf8');
const source = JSON.parse(raw.replace(/"(\d[^"\\]*)"(?=\s*:)/g, `"${MARK}$1"`));
const unmark = (key) => (key.startsWith(MARK) ? key.slice(1) : key);

const families = new Set();
const platforms = new Set();
const features = {};

for (const feature of source.data) {
    const stats = {};
    for (const [family, byPlatform] of Object.entries(feature.stats)) {
        families.add(family);
        stats[family] = {};
        for (const [platform, byVersion] of Object.entries(byPlatform)) {
            platforms.add(platform);
            const versions = Object.entries(byVersion);
            const [version, support] = versions[versions.length - 1];
            stats[family][platform] = [unmark(version), support];
        }
    }
    const notes = {};
    for (const [num, text] of Object.entries(feature.notes_by_num ?? {})) notes[unmark(num)] = text;
    features[feature.slug] = { title: feature.title, category: feature.category, stats, notes };
}

const list = (set) => JSON.stringify([...set].sort());

/** Display names from Can I Email for the given keys, falling back to the key itself. */
const names = (set, nicenames) =>
    JSON.stringify(
        Object.fromEntries([...set].sort().map((key) => [key, nicenames?.[key] ?? key])),
    );
const featureLines = Object.entries(features)
    .map(([slug, feature]) => `  ${JSON.stringify(slug)}: ${JSON.stringify(feature)},`)
    .join('\n');

writeFileSync(
    TARGET,
    `// Generated by scripts/build-compat-data.mjs from ${SOURCE}. Do not edit by hand.
// Source: Can I Email (https://www.caniemail.com) by Rémi Parmentier, MIT licensed.
// See data/LICENSE-caniemail.

export const lastUpdate = ${JSON.stringify(source.last_update_date)};

export const families = ${list(families)} as const;

export const platforms = ${list(platforms)} as const;

export type Family = (typeof families)[number];
export type Platform = (typeof platforms)[number];

/** Display names, e.g. "Apple Mail" for "apple-mail". */
export const familyNames: Record<Family, string> = ${names(families, source.nicenames?.family)};

/** Display names, e.g. "Desktop Webmail" for "desktop-webmail". */
export const platformNames: Record<Platform, string> = ${names(platforms, source.nicenames?.platform)};

export interface Feature {
  title: string;
  category: string;
  /** Latest tested version and its raw support string (e.g. "a #1 #3") per client platform. */
  stats: Partial<Record<Family, Partial<Record<Platform, [version: string, support: string]>>>>;
  /** Footnotes referenced by "#n" markers in support strings. */
  notes: Record<string, string>;
}

export const features: Record<string, Feature> = {
${featureLines}
};
`,
);

console.log(
    `${TARGET}: ${Object.keys(features).length} features, ${families.size} families, ${platforms.size} platforms`,
);
